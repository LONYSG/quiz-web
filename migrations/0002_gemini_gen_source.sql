-- ★★ 왜 새 source_id 가 필요한가
--   R011에서 문제 확보 방식을 바꿨다. OpenTDB 수확을 폐기하고 Gemini 로 직접 생성한다.
--   ★ 건우 지시: 이미 적재된 OpenTDB 문제 10건을 지우지 않고, is_active 도 건드리지 않는다.
--     대신 **source_id 로 구분되어야 한다.** 그것이 이 마이그레이션의 목적이다.
--
--   구분이 필요한 이유는 라이선스다 —
--     · OpenTDB 파생 문제는 CC BY-SA 4.0 의 저작자 표시 의무가 있다
--     · 생성 문제는 그 의무가 없다
--   문제 단위로 출처를 알 수 없으면 "어느 문제 때문에 표기가 필요한가" 를 답할 수 없다.
--
-- ★ 라이선스를 왜 그래도 CC-BY-SA-4.0 으로 두는가 (판단이며, 근거를 밝힌다)
--   생성 문제에는 CC BY-SA 의무가 **없다.** 그래서 다른 라이선스로 둘 수도 있었다.
--   그럼에도 같게 두는 이유
--     (1) 저장소가 Public 이고, 이미 'manual'(직접 작성) 소스를 같은 이유로 그렇게 두었다.
--         한 DB 안에서 라이선스가 갈라지면 데이터셋을 배포할 때 문제 단위로 갈라 내야 한다
--     (2) 우리가 저작권자이므로 CC BY-SA 로 두어도 우리에게 잃는 것이 없다
--   ★ 그러나 **화면 표기는 다르다.** 표기 의무는 OpenTDB 문제에만 있다.
--     그래서 R011에서 푸터 문구를 "문제 출처" → "일부 문제 출처" 로 고쳤다.
--   ★ 이것은 법률 자문이 아니다. DATA_LICENSE.md 에 판단으로 기록했다.
--
-- ★ 카테고리 트리(대분류 7 / 중분류 63 / 소분류 294)는 **이 마이그레이션에 넣지 않았다.**
--   근거: 건우가 R011 샘플을 보고 뺄 것·추가할 것을 정한다. 지금 스키마에 박으면
--   다음 라운드에 되돌려야 한다. 이번 라운드 샘플은 적재하지 않으므로 DB 변경이 필요 없다.
--   → 계층 스키마(categories.parent_id / level)는 건우가 목록을 확정한 뒤 0003 으로 넣는다.
