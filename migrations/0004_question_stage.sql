-- =============================================================================
-- 0004. game_questions.selection_stage — 문제 선정이 몇 단계에서 성공했는가
--
-- ★★ 왜 필요한가 (R013 / Q-76 / D-054)
--   R014 에서 "한 게임 안에서 정답이 겹치는 문제를 내지 않는다" 를 구현한다.
--   선정이 3단계 알고리즘이 되었다 —
--     1단계  전원 미경험 AND 정답 미사용
--     2단계  1명 이상 미경험 AND 정답 미사용
--     3단계  ★ 1명 이상 미경험 (정답 중복 허용)
--
--   ★ 3단계로 내려간 것은 "정답 중복 금지가 발동했으나 문제가 부족해 풀었다" 는 뜻이다.
--   ★ 운영자가 그 빈도를 알아야 기준을 조정할 수 있다 (04-PROTOCOL 3장).
--   ★ 화면에는 표시하지 않는다 — 플레이어에게 알릴 이유가 없다.
--
-- ★ NULL 을 허용한다. 0004 이전에 기록된 행에는 값이 없다.
--   ★ 기본값을 넣어 과거 행을 1단계로 단정하면 통계가 거짓이 된다.
-- =============================================================================

ALTER TABLE game_questions
  ADD COLUMN IF NOT EXISTS selection_stage smallint
    CHECK (selection_stage IN (1, 2, 3));

COMMENT ON COLUMN game_questions.selection_stage IS
  '문제 선정이 성공한 단계 (1=전원미경험+정답미사용 / 2=일부미경험+정답미사용 / 3=정답중복허용). NULL=0004 이전 기록';
