const mk = (slug, items, list, unsure) => {
  const issues = list.map(([n, name, fools, extra]) => {
    const probs = [...(extra || [])];
    const fool = [];
    for (const [f, v, alt, d] of fools || []) {
      fool.push({ f, v, alt: alt ?? null });
      probs.push({ t: 'fool', d: `${f} — ${d}`, fix: alt ? `${f} → ${alt}` : `${f} 제거` });
    }
    const o = { id: `${slug}-${n}`, name, probs };
    if (fool.length) o.fool = fool;
    return o;
  });
  return { items, seen: items, issues, unsure, okCount: items - issues.length };
};
