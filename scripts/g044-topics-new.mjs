const parse = (s) => s.split(';').map((e) => e.trim()).filter(Boolean).map((e) => {
  const [name, v, tag, f] = e.split('|');
  return { name: name.trim(), variants: v ? v.split(',').map((x) => x.trim()).filter(Boolean) : [], tag: tag?.trim() || null, d0: (f ?? '').trim() === 'd0' };
});

export function buildSets() {
  return SETS.map((s) => {
    const items = parse(s.items).map((x, i) => ({
      id: `${s.topic}-${String(i + 1).padStart(3, '0')}`,
      name: x.name,
      variants: x.variants,
      tags: x.tag ? [x.tag] : [],
      draw: x.d0 ? false : s.draw,
      liar: s.liar,
      qid: null,
    }));
    return {
      topic: s.topic, nameKo: s.nameKo, kind: 'open', version: 1, asOf: TODAY, createdRound: 'G044', status: 'candidate',
      source: [{ url: s.source.url, note: s.source.note, fetchedAt: TODAY, read: s.source.read }],
      liar: items.some((i) => i.liar), draw: items.some((i) => i.draw), timeSec: 30, tags: s.tags, count: items.length, items, verify: null,
    };
  });
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/g044-topics-new.mjs')) {
  for (const t of buildSets()) {
    const f = path.join(DIR, `${t.topic}.json`);
    console.log(t.topic.padEnd(16), 'n', t.count, 'liar', t.items.filter((i) => i.liar).length, 'draw', t.items.filter((i) => i.draw).length, existsSync(f) ? '(있음 — 덮어씀)' : '');
    if (APPLY) writeFileSync(f, JSON.stringify(t, null, 1) + '\n');
  }
  if (!APPLY) console.log('dry-run (--apply 로 씀)');
}
