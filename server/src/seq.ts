//
// ★ number 로 충분하다. Number.MAX_SAFE_INTEGER(약 9.007e15)까지 안전하므로
//   이 프로젝트에서 넘칠 일이 없다. BigInt 는 불필요한 복잡도다.
//
// ★ 프로세스가 재시작되면 0부터 다시 시작한다. 그래도 되는 이유:
//   재시작하면 진행 중이던 게임 자체가 사라지고(bootCleanup),
//   통계와 사후 검증은 answer_events.response_ms 로 한다.
//   seq 는 같은 문제 안의 순서 확인에만 쓴다.
// =============================================================================

let counter = 0;

export function nextSeq(): number {
  counter += 1;
  return counter;
}

export function currentSeq(): number {
  return counter;
}
