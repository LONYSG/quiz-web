/**
 * 모델 구성.
 *
 * ★ R010 실측으로 확정했다 (docs/07-DECISIONS.md D-033).
 *   목록에 있다고 쓸 수 있는 것이 아니다 — R005에서 gemini-2.5-flash 계열이
 *   목록에는 있는데 generateContent 는 404 였다.
 *   ★ 그리고 한 번의 503 을 "쓸 수 없다" 로 단정해서도 안 된다.
 *     503 "experiencing high demand" 는 일시적이다. 재시도로 구분해야 한다.
 */
export const MODELS = {
  /**
   * 1차 가공 체인. 복수 정답 배열 생성 + 정답 유일성 판정.
   * ★ 둘 다 모델 지능이 산출물 품질을 직접 좌우하므로 쓸 수 있는 가장 높은 모델을 쓴다.
   *
   * ★★ 왜 하나가 아니라 체인인가 (R010 실측 / D-033)
   *   상위 모델은 **503 "experiencing high demand" 가 자주 난다.**
   *   실측: 실제 크기 프롬프트(3,796자)에서
   *     gemini-3.8-flash  5회째 시도에 성공 (3+6+12+24초 대기)
   *     gemini-3.7-flash  2회째 시도에 성공 (3초 대기)
   *     gemini-3.6-flash  1회째 성공
   *   ★ 품질은 세 모델 모두 함정 6/6 회피, 인명 성만 표기 모두 포함으로 차이가 없었다.
   *
   *   ★ 그래서 "가장 높은 모델을 쓰되, 과부하면 한 단계 내려간다" 를 코드로 구현한다.
   *     앞의 것을 재시도 상한까지 시도하고 안 되면 다음 것으로 넘어간다.
   *   ★ 어떤 모델이 실제로 만들었는지는 항목마다 기록한다(meta.processModel).
   *     그러지 않으면 review_queue.ai_model 이 거짓이 된다.
   */
  processChain: ['gemini-3.8-flash', 'gemini-3.7-flash', 'gemini-3.6-flash'] as const,

  /**
   * 역검증 체인. 가공된 한국어 질문만 보고 정답을 맞혀본다.
   * ★ 1차와 **다른** 모델이어야 한다. 같은 모델을 두 번 쓰면 같은 방향으로 틀리는
   *   상관관계가 생겨 검증이 무의미해진다.
   *   ★ 그래서 실제로 1차 가공에 쓰인 모델을 체인에서 제외하고 고른다.
   *     pickBackcheckChain() 이 그 일을 한다.
   * ★ 정답을 맞힐 지능은 필요하다. 너무 약한 모델을 쓰면 정상 문제를 못 맞혀
   *   false reject 가 늘어난다. 그래서 lite 가 아니라 flash 급을 쓴다.
   */
  backcheckChain: ['gemini-3.7-flash', 'gemini-3.6-flash', 'gemini-3.5-flash'] as const,

  /** 판단이 단순한 보조 작업. 가볍고 저렴한 모델 */
  assist: 'gemini-3.5-flash-lite',
} as const;

/**
 * ★ 역검증 체인에서 1차 가공에 쓴 모델을 뺀다.
 *   같은 모델로 역검증하면 상관관계가 생겨 검증이 무의미해진다.
 */
export function pickBackcheckChain(processModelUsed: string): string[] {
  const chain = MODELS.backcheckChain.filter((m) => m !== processModelUsed);
  // ★ 전부 걸러지는 일은 없지만, 그렇게 되면 검증을 건너뛰는 것보다 낫다
  return chain.length > 0 ? [...chain] : [MODELS.assist];
}

