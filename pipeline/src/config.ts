/**
 * ★ "그날" 의 기준 시각대.
 *
 * ★ Google 의 무료 티어 일일 한도 리셋 기준은 **확인 불가**다.
 *   공식 문서가 무료 티어 수치 자체를 공개하지 않고, 응답 헤더에도 리셋 정보가 없다
 *   (R005·R010 실측).
 *
 * ★ 그래서 보수적으로 정한다: **UTC 자정**을 기준으로 한다.
 *   근거: Google Cloud 의 다른 일일 할당량이 대체로 태평양 시간 또는 UTC 자정 기준이며,
 *   KST(UTC+9)를 기준으로 잡으면 실제 리셋보다 **먼저** 우리 카운터가 초기화될 수 있다.
 *   그러면 "우리는 새 날인데 Google 은 아직 어제" 인 구간이 생겨 429 를 맞는다.
 *   ★ UTC 는 KST 보다 늦게 바뀌므로(KST 09:00 = UTC 00:00) 우리가 더 늦게 초기화된다.
 *     늦게 초기화되는 쪽이 안전하다.
 */
