//   ★ subNotes 를 모든 소분류에 적지 않은 이유 (기술 판단)
//     경계 문장은 생성 프롬프트에 그대로 들어간다. 자명한 것까지 적으면
//     ★ 프롬프트가 길어져 정말 중요한 경계가 묻힌다. 겹칠 위험이 있는 곳에만 적는다.
