// ★★ R010까지는 OpenTDB 문제를 **가공**했다. 이제 **생성**한다.
//   가공과 생성은 위험이 다르다 —
//     가공: 원본이 사실이라는 전제가 있다. 위험은 번역과 정답 유일성이다
//     생성: ★ 모델이 사실을 틀리게 만들 수 있고, 애매한 문제를 지어낼 수 있다
//   → 그래서 역검증을 유지한다. 건우의 지시이기도 하다 ("어느 경우에도 유지한다").
//
// ★★ 접근성과 난이도를 분리한 이유 (건우 지시)
//   R010의 krAccessible 하나로는 다음 둘이 섞였다.
//     "한국인 대부분이 아는 분야의 어려운 문제" (조선 왕 순서)   → 좋다
//     "특정 집단만 아는 분야의 쉬운 문제" (페르소나5 캐릭터 이름) → 나쁘다
//   실제로 R010에서 페르소나5 문제가 krAccessible=3 으로 통과했다.
//   그 3은 "게임 하는 사람은 안다" 는 뜻이었고 난이도가 적당하다는 뜻이 아니었다.
//   → 두 축으로 쪼갠다. 접근성은 **분야**의 성질, 난이도는 **문항**의 성질이다.
//
// ★ 카테고리는 입력이다 (C-2). 모델이 카테고리를 정하지 않는다.
//   대신 "이 카테고리에 맞는 문제를 만들 수 없다" 고 말할 여지만 남긴다
//   (offCategory). 그것은 탈락 사유다.
//
// ─────────────────────────────────────────────────────────────────────────────
// ★★ g3 (R012): 세 번째 축 worthKnowing(알 가치)을 넣었다. 건우 검수 결과다.
//
//   건우가 R011 샘플 257건을 직접 읽고 판단한 것 —
//     "난이도는 다 괜찮다. 접근성 수치가 중요한 것 같다.
//      ★ 난이도가 높아서 아무도 몰랐더라도 알아가면 좋은 상식이라면 불만 없다."
//     "카테고리가 문제가 아니라 ★ 진짜 엉뚱한 퀴즈만 거르면 된다.
//      (누군지도 모르고 일반적인 교과 과정에서 배우지도 않는,
//       알 필요도 없는 사람 이름이나 연도 문제 등)"
//
//   ★ 즉 걸러야 할 기준은 "어려운가" 가 아니라 "알 가치가 있는가" 다.
//   ★★ 그리고 내(설계 담당) R011 판단이 과했다는 것이 확인되었다 —
//     나는 "아무도 못 맞히면 30초가 낭비된다" 며 접근성 하한 4를 권했다.
//     ★ 그런데 정답 공개 5초에 해설이 나온다(guide 21절). 낭비가 아니라 배우는 시간이다.
//     게임에 그 장치가 이미 있는데 그것을 계산에 넣지 않았다.
//
//   세 축의 관계
//     접근성 (accessibility)  이 **분야**를 아는가        → 하한을 건다 (Q-69)
//     난이도 (difficulty)     이 **문항**이 어려운가       → ★ 걸러내지 않는다
//     알 가치 (worthKnowing)  ★ 답을 듣고 "알아서 좋았다" 고 느끼는가 → 하한을 건다
// ─────────────────────────────────────────────────────────────────────────────
