// =============================================================================
// 문제 생성 프롬프트 (작업 D-1 / R011)
//
// ★★ R010까지는 OpenTDB 문제를 **가공**했다. 이제 **생성**한다.
//   가공과 생성은 위험이 다르다 —
//     가공: 원본이 사실이라는 전제가 있다. 위험은 번역과 정답 유일성이다
//     생성: ★ 모델이 사실을 틀리게 만들 수 있고, 애매한 문제를 지어낼 수 있다
//   → 그래서 역검증을 유지한다. 건우의 지시이기도 하다 ("어느 경우에도 유지한다").
//
// ★★ 접근성과 난이도를 분리한 이유 (건우 지시)
//   R010의 krAccessible 하나로는 다음 둘이 섞였다.
//     "한국인 대부분이 아는 분야의 어려운 문제" (조선 왕 순서)   → 좋다
//     "특정 집단만 아는 분야의 쉬운 문제" (페르소나5 캐릭터 이름) → 나쁘다
//   실제로 R010에서 페르소나5 문제가 krAccessible=3 으로 통과했다.
//   그 3은 "게임 하는 사람은 안다" 는 뜻이었고 난이도가 적당하다는 뜻이 아니었다.
//   → 두 축으로 쪼갠다. 접근성은 **분야**의 성질, 난이도는 **문항**의 성질이다.
//
// ★ 카테고리는 입력이다 (C-2). 모델이 카테고리를 정하지 않는다.
//   대신 "이 카테고리에 맞는 문제를 만들 수 없다" 고 말할 여지만 남긴다
//   (offCategory). 그것은 탈락 사유다.
// =============================================================================

import { findMajor, type MidCategory } from './categories.js';

/** 생성 프롬프트 버전. 프롬프트를 고치면 올린다 */
export const GEN_PROMPT_VERSION = 'g2';

/** 한 슬롯 = "이 중분류의 이 소분류로 문제 하나" */
export interface GenSlot {
  /** 모델 응답과 우리 요청을 맞추는 열쇠. 예: religion#1 */
  slotId: string;
  midKey: string;
  midNameKo: string;
  majorNameKo: string;
  sub: string;
  boundary?: string;
}

/** ★ 생성 응답 스키마. required 로 필드를 강제한다 (R005 교훈) */
export const GENERATE_SCHEMA = {
  type: 'object',
  properties: {
    items: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          slotId: { type: 'string' },
          question: { type: 'string' },
          displayAnswer: { type: 'string' },
          answers: { type: 'array', items: { type: 'string' } },
          hintAnswer: { type: 'string' },
          // ★ 두 축을 분리한다
          accessibility: { type: 'integer' },
          difficulty: { type: 'integer' },
          explanation: { type: 'string' },
          answerLang: { type: 'string', enum: ['ko', 'en', 'mixed'] },
          // ★ 요청 카테고리에 맞지 않으면 true. 그것이 탈락 사유가 된다
          offCategory: { type: 'boolean' },
          offCategoryReason: { type: 'string' },
          confidence: { type: 'number' },
        },
        required: [
          'slotId',
          'question',
          'displayAnswer',
          'answers',
          'accessibility',
          'difficulty',
          'answerLang',
          'offCategory',
          'confidence',
        ],
      },
    },
  },
  required: ['items'],
} as const;

export interface GenItem {
  slotId: string;
  question: string;
  displayAnswer: string;
  answers: string[];
  hintAnswer?: string;
  accessibility: number;
  difficulty: number;
  explanation?: string;
  answerLang: 'ko' | 'en' | 'mixed';
  offCategory: boolean;
  offCategoryReason?: string;
  confidence: number;
}

export function buildGeneratePrompt(slots: GenSlot[]): string {
  const list = slots
    .map((s) => {
      const head = `- slotId "${s.slotId}" → [${s.majorNameKo} > ${s.midNameKo} > ${s.sub}]`;
      return s.boundary ? `${head}\n    경계: ${s.boundary}` : head;
    })
    .join('\n');

  return `너는 한국어 실시간 멀티플레이 퀴즈 게임의 출제자다.
아래 슬롯 목록에 지정된 카테고리마다 주관식 단답 문제를 **정확히 하나씩** 만든다.

★★ 이 게임은 정답을 "정확한 문자열 일치"로만 판정한다.
오타 허용도, 유사도 판정도, 부분 점수도 없다.
따라서 정답이 조금이라도 애매한 문제는 만들면 안 된다.
좋은 문제를 적게 만드는 것이 애매한 문제를 많이 만드는 것보다 낫다.

────────────────────────────────
[절대 만들지 말아야 하는 문제]
────────────────────────────────
1. ★ 정답이 유일하지 않은 문제
   나쁜 예: "가장 유명한 화가는?"  (기준이 없다. 사람마다 다르다)
   나쁜 예: "유럽의 나라 하나를 대라?"  (답이 수십 개다)
   나쁜 예: "빨간색이 들어간 국기를 가진 나라는?"  (답이 여럿이다)
   ★ "가장 ~한", "대표적인", "유명한", "잘 알려진" 같은 주관적 수식어를 쓰지 마라.
     단, 객관적 1위가 확정된 것은 괜찮다 ("세계에서 가장 높은 산은?" → 에베레스트).
2. ★ 시간이 지나면 답이 바뀌는 문제
   나쁜 예: "현재 대한민국 대통령은?"  "최근 월드컵 우승국은?"
   나쁜 예: "세계에서 가장 높은 건물은?"  (새 건물이 지어진다)
   ★ 이 게임은 문제를 데이터베이스에 장기 보관한다. 오늘 맞는 답이 아니라
     10년 뒤에도 맞는 답이어야 한다.
3. ★ 정답이 서술형인 문제
   나쁜 예: "광합성이 일어나는 이유는?"  (표현이 사람마다 다르다)
   ★ 정답은 짧고 명확한 명사 하나여야 한다. 문장이나 설명은 정답이 될 수 없다.
4. ★★ 질문 안에 정답이 들어 있는 문제 — **answers 배열의 어느 표기도 마찬가지다**
   나쁜 예: "조선의 4대 왕 세종대왕이 만든 문자는?"  (세종이 이미 나와 있다)
   ★★ 아래가 실제로 가장 많이 나온 실패다. 반드시 피하라.
     나쁜 예: "국왕의 권력을 제한한 **대헌장**의 라틴어 명칭은?" → 마그나 카르타
              (answers 에 "대헌장" 을 넣으면서 질문에도 써 버렸다)
     나쁜 예: "**샹파뉴** 지역에서 생산되는 발포성 와인은?" → 샴페인
              (answers 에 "샹파뉴" 를 넣으면서 질문에도 써 버렸다)
     나쁜 예: "방바닥 밑의 **구들장**을 덥히는 난방 방식은?" → 온돌
              (answers 에 "구들장" 을 넣으면서 질문에도 써 버렸다)
     나쁜 예: "'**목폴라**'라고도 불리는 스웨터 형태는?" → 터틀넥
              (answers 에 "목폴라" 를 넣으면서 질문에도 써 버렸다)
   ★ 왜 치명적인가: 이 게임은 채팅으로 정답을 받는다.
     질문에 적힌 낱말을 그대로 옮겨 치면 아무것도 모르는 사람이 이긴다.
   ★ 규칙: **answers 에 넣을 표기는 질문 문장에 등장해서는 안 된다.**
     질문에 그 낱말을 쓸 수밖에 없다면, 그 표기를 answers 에서 빼는 것이 아니라
     ★ 질문을 다르게 쓴다. 표기를 빼면 그 표기로 답한 사람이 억울하게 진다.
5. 숫자 정답인데 단위·정밀도 표기가 여러 가지인 문제
   나쁜 예: "지구의 반지름은?"  (6371km / 6,371 / 약 6400 …)
   괜찮은 예: "축구 한 팀의 선수는 몇 명인가?" → 11
6. 여러 항목을 나열해야 하는 문제, 보기를 전제하는 문제 ("다음 중 ~")

────────────────────────────────
[점수 두 가지 — ★ 반드시 구분해서 매겨라]
────────────────────────────────
★ 이 둘은 완전히 다른 축이다. 섞으면 안 된다.

accessibility (접근성) — **이 분야를 일반적인 한국 성인이 아는가.** 1~5
  5 = 한국의 초·중·고 교과 과정이나 국민 대다수가 아는 대중문화에 속한다
  4 = 대부분의 성인이 들어는 봤다
  3 = 관심 있는 사람은 알지만 아닌 사람은 전혀 모른다
  2 = 특정 팬덤·전공자 집단만 안다
  1 = 해당 국가·해당 커뮤니티 밖에서는 사실상 아무도 모른다
  ★ 문항이 쉬운지 어려운지는 여기서 판단하지 마라. **분야**를 판단하라.

difficulty (난이도) — **그 분야를 아는 사람에게 이 문항이 어려운가.** 1~5
  5 = 그 분야를 잘 아는 사람도 헷갈린다
  3 = 그 분야를 아는 사람은 대체로 안다
  1 = 그 분야를 조금이라도 아는 사람이면 반드시 안다
  ★ 분야가 얼마나 알려졌는지는 여기서 판단하지 마라. **문항**을 판단하라.

★ 예로 감을 잡아라.
  "훈민정음을 만든 왕은?"        → 접근성 5 / 난이도 1
  "조선의 제7대 왕은?"           → 접근성 5 / 난이도 4  (분야는 누구나 아나 문항이 어렵다)
  "페르소나5 주인공의 학교 이름?" → 접근성 1 / 난이도 2  (팬은 쉽게 답하나 분야가 좁다)
  "베르누이 정리를 쓰는 현상은?"   → 접근성 3 / 난이도 3

★ 접근성을 후하게 주지 마라. 자기가 아는 것을 남도 안다고 가정하지 마라.
  판단 기준은 "한국의 평범한 40대가 이 분야를 아는가" 다.

────────────────────────────────
[정답 표기 변형 — answers 배열. ★ 가장 중요한 필드다]
────────────────────────────────
게임은 정확 문자열 일치로만 판정하므로, 실제 사람이 칠 법한 표기를 최대한 넣어라.
넣지 않은 표기로 답한 사람은 정답을 알면서도 오답 처리된다.

반드시 포함할 것
  - displayAnswer 자체
  - 원문 표기 (영문·한자 등. 예: Stack, 訓民正音)
  - 한글 음차의 흔한 변형 (예: 반 고흐 / 빈센트 반 고흐 / 고흐 / 반고흐)
  - ★ 인명은 성만 표기도 반드시 넣는다. 서양 인명이든 동양 인명이든 동일하다
      "너새니얼 호손" → "호손"
      "코지마 히데오" → "코지마"
      "이순신" → 성만 표기가 의미 없으면 넣지 않는다 (한국 인명은 보통 전체를 쓴다)
  - 한자어와 고유어가 함께 쓰이면 양쪽 (예: 계란 / 달걀)
  - ★ 숫자는 아라비아 숫자와 한글 표기 양쪽 (예: 11 / 열한 / 십일)
  - 널리 쓰이는 약칭·별칭 (예: 서울대학교 → 서울대)

넣지 말 것
  - 명백히 틀린 답
  - ★ 정답보다 넓은 상위 개념 (정답이 "서울"인데 "한국"을 넣지 않는다)
  - ★ 정답보다 좁은 하위 개념 (정답이 "영국"인데 "잉글랜드"를 넣지 않는다)
  - 오타 변형 (오타를 허용하지 않는 것이 이 게임의 규칙이다)

★ 띄어쓰기 차이와 영문 대소문자 차이는 게임 엔진이 알아서 무시한다.
  그 목적만으로 변형을 추가하지 마라.

────────────────────────────────
[카테고리 — ★ 우리가 지정한다]
────────────────────────────────
★ 카테고리는 이미 정해져 있다. 네가 고르는 값이 아니다.
  슬롯에 적힌 [대분류 > 중분류 > 소분류] 에 맞는 문제를 만들어라.
  소분류가 그 문제의 소재 범위다. 다른 소분류의 소재를 쓰지 마라.

★ 경계가 적혀 있으면 반드시 지켜라. 인접 카테고리의 소재를 침범하면
  같은 문제가 두 카테고리에 생겨 중복 검사가 무력해진다.

★ 그 카테고리로 위 조건을 모두 만족하는 문제를 만들 수 없다면
  offCategory=true 로 하고 offCategoryReason 에 한 문장 이유를 써라.
  ★ 억지로 만들지 마라. 억지로 만든 문제가 실전에 나가는 것이 더 나쁘다.
  offCategory=true 인 경우에도 slotId 는 반드시 채워라.

────────────────────────────────
[생성할 필드]
────────────────────────────────
slotId            — 슬롯 목록의 값을 그대로 되돌려라. 이것으로 요청과 맞춘다
question          — 한국어 질문. 존댓말을 쓰지 않고 "~은?", "~는 무엇인가?" 형태로 간결하게
displayAnswer     — 정답 공개 화면에 보여줄 대표 표기 하나
answers           — 위 규칙에 따른 표기 변형 배열 (displayAnswer 포함)
hintAnswer        — 힌트 생성 기준으로 삼을 정답 하나. 보통 displayAnswer 와 같다
accessibility     — 1~5 (분야)
difficulty        — 1~5 (문항)
explanation       — 한 문장 해설. 정답을 왜 그렇게 판단하는지
answerLang        — displayAnswer 가 한국어면 "ko", 영문이면 "en", 섞였으면 "mixed"
offCategory       — 위 설명 참조. 정상 생성이면 false
offCategoryReason — offCategory=false 면 빈 문자열
confidence        — 사실 정확성에 대한 자기 확신. 0.0~1.0

────────────────────────────────
[제출 전 자기 점검 — ★ 각 문항마다 확인하라]
────────────────────────────────
1. answers 의 표기 중 하나라도 question 안에 등장하는가? → 등장하면 question 을 고친다
2. answers 의 각 표기가 짧은 명사인가? (마침표로 끝나거나 단어 5개 이상이면 안 된다)
3. 10년 뒤에도 같은 답인가?
4. 조건을 만족하는 다른 답이 현실에 또 있는가? → 있으면 question 을 좁힌다
5. displayAnswer 가 answers 에 들어 있는가?

★ 슬롯은 ${slots.length}개다. items 도 정확히 ${slots.length}개여야 한다.
★ 같은 정답을 두 슬롯에 쓰지 마라. 이 요청 안에서 정답이 겹치지 않게 하라.

슬롯 목록:
${list}`;
}

/**
 * 카테고리 트리에서 슬롯 목록을 만든다.
 *
 * @param subOffset ★ 소분류 시작 위치. 같은 중분류를 두 번째로 돌 때 쓴다.
 *   ★ 오프셋 없이 두 번 돌리면 **같은 소분류를 다시 요청**해 중복이 난다.
 *     규모를 늘릴 때는 소분류를 넓게 돌아야 한다 (C-4 지시).
 */
export function buildSlots(mids: MidCategory[], perMid: number, subOffset = 0): GenSlot[] {
  const slots: GenSlot[] = [];
  for (const mid of mids) {
    const major = findMajor(mid.major);
    for (let i = 0; i < perMid; i += 1) {
      // ★ 소분류를 돌려 쓴다. 같은 소분류에 몰리면 한 요청 안에서 중복이 난다
      const sub = mid.subs[(i + subOffset) % mid.subs.length] ?? mid.subs[0]!;
      slots.push({
        slotId: `${mid.key}#${i + 1 + subOffset}`,
        midKey: mid.key,
        midNameKo: mid.nameKo,
        majorNameKo: major?.nameKo ?? mid.major,
        sub,
        boundary: mid.boundary,
      });
    }
  }
  return slots;
}
